// Project map: where every part and function of SpeedTAS lives, as an upgrade tree.
//   node scripts/project-map.mjs          rewrite docs/project-map.md from the code
//   node scripts/project-map.mjs --check  fail if docs/project-map.md is out of date or a function belongs to no part
// The tree (parts, plain descriptions, what uses what) is in scripts/project-map.json; files, line ranges and
// functions are read from the code each time, so line numbers are always exact. A part's "where" entry is
// [file], [file, from, to], {path, start_pat, end_pat} (a section found by regex) or a plain text note.
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';

const { nodes, fdesc } = JSON.parse(readFileSync('scripts/project-map.json', 'utf8'));
const OUT = 'docs/project-map.md';
const fileLines = (p) => readFileSync(p, 'utf8').split('\n');
const funcs = (p) => fileLines(p).flatMap((l, i) => { const m = l.match(/^\s*(?:export\s+)?(?:async\s+)?function\s+([A-Za-z0-9_$]+)/); return m ? [{ n: m[1], l: i + 1 }] : []; });
const part = (file, from = 1, to = null) => {
  const lines = fileLines(file), end = to || lines.length - (lines[lines.length - 1] === '' ? 1 : 0);
  return { file, from, to: end, fns: funcs(file).filter((f) => f.l >= from && f.l <= end) };
};
const section = ({ path, start_pat, end_pat }) => {
  const lines = fileLines(path), a = lines.findIndex((l) => new RegExp(start_pat).test(l));
  if (a < 0) throw new Error(`project map: "${start_pat}" not found in ${path}`);
  const b = end_pat ? lines.findIndex((l, i) => i > a && new RegExp(end_pat).test(l)) : -1;
  return part(path, a + 1, b < 0 ? null : b);
};
for (const n of nodes) n.places = (n.where || []).map((w) => (typeof w === 'string' ? { note: w } : Array.isArray(w) ? part(...w) : section(w)));

// Every function in the code belongs to exactly one part.
const codeFiles = [...readdirSync('assets/js').map((f) => `assets/js/${f}`), ...readdirSync('scripts').filter((f) => f.endsWith('.mjs')).map((f) => `scripts/${f}`), ...readdirSync('scripts/lib').map((f) => `scripts/lib/${f}`)];
const owner = {};
for (const n of nodes) for (const p of n.places) for (const f of p.fns || []) (owner[`${p.file}:${f.n}:${f.l}`] = owner[`${p.file}:${f.n}:${f.l}`] || []).push(n.id);
const problems = [];
for (const file of codeFiles) for (const f of funcs(file)) {
  const o = owner[`${file}:${f.n}:${f.l}`];
  if (!o) problems.push(`${file}:${f.l} ${f.n} belongs to no part (add its file or section to scripts/project-map.json)`);
  else if (o.length > 1) problems.push(`${file}:${f.l} ${f.n} is in several parts: ${o.join(', ')}`);
}

const byId = Object.fromEntries(nodes.map((n) => [n.id, n]));
const kids = (id) => nodes.filter((n) => n.parent === id);
const total = nodes.reduce((a, n) => a + n.places.reduce((b, p) => b + (p.fns || []).length, 0), 0);
const md = [`# SpeedTAS project map`, '',
  `Generated by \`npm run map\` (scripts/project-map.mjs) from the code; do not edit by hand. ${nodes.length - 1} parts, ${total} functions.`,
  'The tree, descriptions and links are in scripts/project-map.json. Line numbers are exact for the commit this file was generated with.', ''];
const tree = (id, depth) => { const n = byId[id]; md.push(`${'  '.repeat(depth)}- ${n.title}`); kids(id).forEach((k) => tree(k.id, depth + 1)); };
md.push('## Tree', ''); tree('root', 0); md.push('');
const walkNode = (id, depth) => {
  const n = byId[id];
  md.push(`${'#'.repeat(Math.min(depth + 2, 4))} ${n.title}`, '', n.what);
  if (n.tip) md.push('', `Good to know: ${n.tip}`);
  if (n.places.length) md.push('');
  for (const p of n.places) {
    if (p.note) { md.push(`- ${p.note}`); continue; }
    md.push(`- \`${p.file}\` lines ${p.from}–${p.to}${p.fns.length ? ':' : ''}`);
    for (const f of p.fns) md.push(`  - \`${f.n}\` ${f.l}${fdesc[f.n] ? ` — ${fdesc[f.n]}` : ''}`);
  }
  if ((n.uses || []).length) md.push('', `Uses: ${n.uses.map((u) => byId[u].title).join(', ')}`);
  const usedBy = nodes.filter((m) => (m.uses || []).includes(id));
  if (usedBy.length) md.push(`Used by: ${usedBy.map((m) => m.title).join(', ')}`);
  md.push('');
  kids(id).forEach((k) => walkNode(k.id, depth + 1));
};
walkNode('root', 0);
const text = md.join('\n');

if (process.argv.includes('--check')) {
  let current = ''; try { current = readFileSync(OUT, 'utf8'); } catch {}
  if (current !== text) problems.push(`${OUT} is out of date: run npm run map and commit it`);
  if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
  console.log(`project map up to date (${nodes.length - 1} parts, ${total} functions)`);
} else {
  mkdirSync('docs', { recursive: true });
  writeFileSync(OUT, text);
  if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
  console.log(`project map: ${nodes.length - 1} parts, ${total} functions -> ${OUT}`);
}
